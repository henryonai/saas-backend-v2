/**
 * Writes src/shared/api/generated/ from the backend, so the app's types can't
 * drift from it:
 *   <module>.ts  types from each module's OpenAPI document (scripts/export-openapi.py)
 *   plans.json   the plan catalog (layers/shared/layer/shared/plans.py)
 *
 * Needs the backend's environment (`uv sync --all-packages` at the repository
 * root). CI runs this and fails if the result differs from what is committed.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(web, '..');
const docs = path.join(root, 'docs/openapi');
const out = path.join(web, 'src/shared/api/generated');
const BANNER = '// Generated by `pnpm gen:api` from the backend. Do not edit.\n\n';
const PLANS = 'import json; from shared.plans import DEFAULT_PLAN, PLANS; ' +
  'print(json.dumps({"default": DEFAULT_PLAN, "plans": PLANS}, indent=2))';

execFileSync('uv', ['run', 'python', 'scripts/export-openapi.py'], { cwd: root, stdio: 'inherit' });

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const file of readdirSync(docs).filter((name) => name.endsWith('.json')).sort()) {
  const ast = await openapiTS(pathToFileURL(path.join(docs, file)));
  const target = path.join(out, file.replace(/\.json$/, '.ts'));
  writeFileSync(target, BANNER + astToString(ast));
  console.log(path.relative(web, target));
}

writeFileSync(path.join(out, 'plans.json'), execFileSync('uv', ['run', 'python', '-c', PLANS], { cwd: root, encoding: 'utf8' }));
console.log(path.relative(web, path.join(out, 'plans.json')));
